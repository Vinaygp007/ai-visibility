import type { AnalysisResult, CitationResult, ProviderMeta, Recommendation, UserPlan } from "@/types";
import { extractProviderText } from "@/lib/plainText";

// Minimal row shape (matches BulkRow in app/bulk/page.tsx) so this module
// stays independent of the page component.
export interface MarkdownBulkRow {
  url: string;
  status: string;
  score?: number;
  grade?: string;
  site_name?: string;
  summary?: string;
  error?: string;
  fullData?: AnalysisResult;
}

// Table cells can't contain raw pipes or newlines.
function cell(v: unknown): string {
  if (v === null || v === undefined || v === "") return "-";
  return String(v).replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ").trim();
}

// Provider answers are themselves Markdown. Their headings would collide with
// the report's own structure (every company is a "##" section), so they are
// flattened to bold lines; everything else is kept as written.
function demoteHeadings(md: string): string {
  return md
    .replace(/\r\n/g, "\n")
    .split("\n")
    .map((line) => {
      const m = line.match(/^\s{0,3}#{1,6}\s+(.*)$/);
      // Blank lines around keep consecutive headings from merging into one
      // paragraph and let a following table render.
      return m ? `\n**${m[1].replace(/\s*#+\s*$/, "")}**\n` : line;
    })
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

function uniq(urls: string[]): string[] {
  return Array.from(new Set(urls.filter(Boolean)));
}

function isWhiteLabelPlan(plan: UserPlan): boolean {
  // Same branding rule as the bulk PDF export: Agency/Scale are white-label.
  return plan === "agency" || plan === "scale";
}

function footer(plan: UserPlan): string[] {
  return isWhiteLabelPlan(plan) ? [] : ["---", "_Generated by AI Scope by Marcstrat_"];
}

// "https://www.vocal-365.com/" -> "vocal-365-com"
function slugFromUrl(url: string): string {
  let host = url;
  try {
    host = new URL(url).hostname;
  } catch {
    /* keep raw string */
  }
  return host.replace(/^www\./, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 60) || "site";
}

function overviewTable(rows: MarkdownBulkRow[]): string {
  return (
    "| # | Company | URL | Score | Grade | Citations | Status |\n|---|---|---|---|---|---|---|\n" +
    rows
      .map((r, i) => {
        const success = r.status === "success" && r.fullData;
        return `| ${i + 1} | ${cell(displayName(r))} | ${cell(r.url)} | ${success ? r.score ?? r.fullData!.overall_score : "-"} | ${success ? cell(r.grade ?? r.fullData!.grade) : "-"} | ${success ? totalCitations(r.fullData) : "-"} | ${success ? "Success" : "Failed"} |`;
      })
      .join("\n")
  );
}

function overviewMarkdown(rows: MarkdownBulkRow[], plan: UserPlan): string {
  const ok = rows.filter((r) => r.status === "success" && r.fullData);
  const scores = ok.map((r) => r.score ?? r.fullData!.overall_score).filter((s) => typeof s === "number");
  const avg = scores.length ? Math.round(scores.reduce((a, b) => a + b, 0) / scores.length) : null;
  const out: string[] = [];
  out.push(isWhiteLabelPlan(plan) ? "# AI Visibility Bulk Report: Overview" : "# AI Scope: AI Visibility Bulk Report: Overview");
  out.push(
    `**Generated:** ${new Date().toLocaleString()}  \n**Companies:** ${rows.length} · **Succeeded:** ${ok.length} · **Failed:** ${rows.length - ok.length}` +
      (avg !== null ? ` · **Average score:** ${avg}/100` : "")
  );
  out.push(overviewTable(rows));
  out.push(
    "_Each company's full report is in its own numbered file. Page Speed and Crawl results run live in the browser and aren't saved with the scan, so they aren't included._"
  );
  out.push(...footer(plan));
  return out.join("\n\n") + "\n";
}

function totalCitations(fd?: AnalysisResult): number {
  return (fd?.citations ?? []).reduce((s, c) => s + (c.count ?? 0), 0);
}

const yesNo = (v: boolean) => (v ? "✅ Yes" : "❌ No");

const CHECK_LABEL: Record<string, string> = { pass: "✅ Pass", warn: "⚠️ Warning", fail: "❌ Fail" };

const PLATFORM_LABEL: Record<string, string> = {
  chatgpt: "ChatGPT",
  claude: "Claude",
  perplexity: "Perplexity",
  gemini: "Gemini",
  meta_ai: "Meta AI",
  you_com: "You.com",
  duckduckgo: "DuckDuckGo",
  apple: "Apple Intelligence",
};

// Saved scans carry stale provider labels ("Gemini 2.0 Flash",
// "ChatGPT (GPT-4o)") alongside current ones, so one model can appear under
// two names in the same report. Show one consistent name per model.
function modelName(raw: string): string {
  const n = raw.toLowerCase();
  if (n.includes("overview")) return "Google AI Overview";
  if (n.includes("gemini")) return "Gemini";
  if (n.includes("chatgpt") || n.includes("gpt") || n.includes("openai")) return "ChatGPT";
  if (n.includes("perplexity")) return "Perplexity";
  if (n.includes("claude") || n.includes("anthropic")) return "Claude";
  if (n.includes("copilot")) return "Microsoft Copilot";
  return raw;
}

// Gemini's grounding returns Google redirect links, not the source pages, so
// their domain says nothing about the source.
function isGoogleRedirect(url: string): boolean {
  return /vertexaisearch\.cloud\.google\.com\/grounding-api-redirect/i.test(url);
}

// HTML entities ("&quot;" -> "quot") that older scans recorded as keywords.
const ENTITY_WORDS = new Set(["quot", "amp", "nbsp", "apos", "rsquo", "lsquo", "rdquo", "ldquo", "ndash", "mdash", "hellip"]);

function displayName(r: MarkdownBulkRow): string {
  const name = r.site_name || r.fullData?.site_name || "";
  let host = "";
  try {
    host = new URL(r.url).hostname.replace(/^www\./, "");
  } catch {
    /* keep empty */
  }
  if (!name) return host || r.url;
  return host && !name.toLowerCase().includes(host.toLowerCase()) ? `${name} (${host})` : name;
}

// Same logic as the Mentions list in components/CitationsPanel.tsx: brand
// names taken from the domains of the cited pages (Google redirects skipped).
function extractMentions(urls: string[]): string[] {
  const names = urls
    .filter((u) => !isGoogleRedirect(u))
    .map((u) => {
      try {
        return new URL(u).hostname.replace(/^www\./, "").split(".")[0];
      } catch {
        return null;
      }
    })
    .filter((s): s is string => !!s)
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1));
  return uniq(names).slice(0, 8);
}

// Each model's audit answer is stored as the JSON it returned:
// { summary, recommendations: [{ priority, title, description, impact }] }.
function parseAudit(raw?: string): { summary?: string; recommendations?: Recommendation[] } | null {
  if (!raw) return null;
  try {
    const parsed = JSON.parse(raw);
    return parsed && typeof parsed === "object" ? parsed : null;
  } catch {
    return null;
  }
}

function recommendationsTable(recs: Recommendation[]): string {
  return (
    "| # | Priority | Recommendation | What to do | Expected impact |\n|---|---|---|---|---|\n" +
    recs
      .map((rec, i) => `| ${i + 1} | ${cell(rec.priority?.toUpperCase())} | ${cell(rec.title)} | ${cell(rec.description)} | ${cell(rec.impact)} |`)
      .join("\n")
  );
}

function auditSection(p: ProviderMeta): string {
  const out: string[] = [`### ${modelName(p.name)}`];
  if (p.status !== "success") {
    out.push(`_Failed${p.error ? `: ${cell(p.error)}` : ""}_`);
    return out.join("\n\n");
  }
  const audit = parseAudit(p.rawResponse);
  if (!audit) {
    const text = extractProviderText(p.rawResponse);
    out.push(text ? demoteHeadings(String(text)) : "_No response captured._");
    return out.join("\n\n");
  }
  if (audit.summary) out.push(`**Summary:** ${audit.summary}`);
  if (Array.isArray(audit.recommendations) && audit.recommendations.length) {
    out.push(recommendationsTable(audit.recommendations));
  }
  return out.join("\n\n");
}

function citationSection(c: CitationResult): string {
  const out: string[] = [`### ${modelName(c.provider)}`];
  if (c.status !== "success") {
    out.push(`_${c.status === "failed" ? "Failed" : "Unavailable"}${c.error ? `: ${cell(c.error)}` : ""}_`);
    return out.join("\n\n");
  }

  const pages = uniq(c.allCitationUrls ?? []);
  const mentions = extractMentions(pages);
  out.push(`**Citations:** ${c.count} · **Cited pages:** ${pages.length} · **Mentions:** ${mentions.length}`);

  out.push("#### Mentions\n\n" + (mentions.length ? mentions.map((m, i) => `${i + 1}. ${m}`).join("\n") : "_No brands extracted._"));

  // Google redirect links are long opaque tokens; show them as short,
  // still-clickable links instead of the raw URL.
  const pageLines = pages.map((u, i) =>
    isGoogleRedirect(u) ? `${i + 1}. [Google Search source ${i + 1}](${u})` : `${i + 1}. ${u}`
  );
  const redirectNote = pages.some(isGoogleRedirect)
    ? "\n\n_Gemini returns Google redirect links rather than the original pages, so the source sites can't be named here._"
    : "";
  out.push("#### Cited Pages\n\n" + (pages.length ? pageLines.join("\n") + redirectNote : "_No source pages captured._"));

  // The saved "snippets" are split on every "." (including inside domains
  // like "finspectors.ai"), which garbles them; the full response below
  // already contains the same text intact.

  if (c.rawAnswer?.trim()) {
    out.push("#### Full Response\n\n<details>\n<summary>Show full response</summary>\n\n" + demoteHeadings(c.rawAnswer) + "\n\n</details>");
  }
  return out.join("\n\n");
}

// One company as a standalone Markdown document. Sections without data are
// skipped; numbering follows whatever is present so it never has gaps.
export function buildCompanyMarkdown(r: MarkdownBulkRow, index: number, plan: UserPlan): string {
  const fd = r.fullData;
  const out: string[] = [`# ${index}. ${displayName(r)}`, `**URL:** ${r.url}`];

  if (r.status !== "success" || !fd) {
    out.push(`**Status:** ❌ Failed${r.error ? `: ${cell(r.error)}` : ""}`);
    return [...out, ...footer(plan)].join("\n\n") + "\n";
  }

  const sections: { title: string; body: string }[] = [];

  // Overview
  const stats = fd.stats;
  const overview: string[] = [
    "| Metric | Value |\n|---|---|\n" +
      [
        `| AI Visibility Score | **${r.score ?? fd.overall_score}/100** |`,
        `| Grade | **${cell(r.grade ?? fd.grade)}** |`,
        `| Total AI citations | ${totalCitations(fd)} |`,
        ...(stats
          ? [
              `| Checks passed | ✅ ${stats.checks_passed} |`,
              `| Warnings | ⚠️ ${stats.checks_warned} |`,
              `| Checks failed | ❌ ${stats.checks_failed} |`,
            ]
          : []),
      ].join("\n"),
  ];
  if (fd.summary) overview.push(`**Summary:** ${fd.summary}`);
  sections.push({ title: "Overview", body: overview.join("\n\n") });

  // AI platform coverage
  const coverage = Object.entries(fd.ai_platform_coverage ?? {}).filter(([, v]) => v);
  if (coverage.length) {
    sections.push({
      title: "AI Platform Coverage",
      body:
        "| Platform | Status |\n|---|---|\n" +
        coverage.map(([k, v]) => `| ${PLATFORM_LABEL[k] ?? k} | ${v === "indexed" ? "✅ Accessible" : "❌ Blocked"} |`).join("\n"),
    });
  }

  // Crawler access, bot by bot
  const bots = fd._botResults ?? [];
  if (bots.length) {
    const blocked = bots.filter((b) => !b.allowed);
    sections.push({
      title: "AI Crawler Access",
      body:
        `**Allowed:** ${bots.length - blocked.length}/${bots.length}` +
        (blocked.length ? ` · **Blocked:** ${blocked.map((b) => b.label).join(", ")}` : " · No AI crawlers blocked") +
        "\n\n| Bot | Company | Access | Reason | robots.txt rule |\n|---|---|---|---|---|\n" +
        bots
          .map((b) => `| ${cell(b.label)} | ${cell(b.company)} | ${b.allowed ? "✅ Allowed" : "❌ Blocked"} | ${cell(b.reason)} | ${b.directive ? "`" + cell(b.directive) + "`" : "-"} |`)
          .join("\n"),
    });
  }

  // Category scores + every individual check
  if (fd.categories?.length) {
    sections.push({
      title: "Category Scores",
      body:
        "| Category | Score |\n|---|---|\n" +
        fd.categories.map((cat) => `| ${cell(cat.name)} | ${cat.score}/100 |`).join("\n"),
    });
    sections.push({
      title: "Detailed Checks",
      body: fd.categories
        .map((cat) => {
          const head = `### ${cat.name} (${cat.score}/100)`;
          if (!cat.checks?.length) return `${head}\n\n_No checks recorded._`;
          return (
            `${head}\n\n| Check | Result | Detail |\n|---|---|---|\n` +
            cat.checks.map((ch) => `| ${cell(ch.label)} | ${CHECK_LABEL[ch.status] ?? ch.status} | ${cell(ch.detail)} |`).join("\n")
          );
        })
        .join("\n\n"),
    });
  }

  if (fd.recommendations?.length) {
    sections.push({ title: "Recommendations", body: recommendationsTable(fd.recommendations) });
  }

  if (fd.keywords?.length) {
    sections.push({
      title: "Top Keywords",
      body:
        "| Keyword | Count | In title | In H1 | In meta description |\n|---|---|---|---|---|\n" +
        fd.keywords.filter((k) => !ENTITY_WORDS.has(k.word)).map((k) => `| ${cell(k.word)} | ${k.count} | ${yesNo(k.inTitle)} | ${yesNo(k.inH1)} | ${yesNo(k.inMeta)} |`).join("\n"),
    });
  }

  // Each model's own audit
  const providers = fd._providers ?? [];
  if (providers.length) {
    sections.push({
      title: "AI Model Audits",
      body:
        "| Model | Status | Score | Response time |\n|---|---|---|---|\n" +
        providers
          .map((p) => `| ${cell(modelName(p.name))} | ${p.status === "success" ? "✅ Success" : "❌ Failed"} | ${p.score ?? "-"} | ${p.durationMs ? `${(p.durationMs / 1000).toFixed(1)}s` : "-"} |`)
          .join("\n") +
        "\n\n" +
        providers.map(auditSection).join("\n\n"),
    });
  }

  // Live citation checks
  const citations = fd.citations ?? [];
  if (citations.length) {
    sections.push({
      title: "AI Citations",
      body:
        "| Model | Status | Citations | Cited pages | Mentions |\n|---|---|---|---|---|\n" +
        citations
          .map((c) => {
            const ok = c.status === "success";
            const pages = uniq(c.allCitationUrls ?? []);
            return `| ${cell(modelName(c.provider))} | ${ok ? "✅ Success" : c.status === "failed" ? "❌ Failed" : "Unavailable"} | ${ok ? c.count : "-"} | ${ok ? pages.length : "-"} | ${ok ? extractMentions(pages).length : "-"} |`;
          })
          .join("\n") +
        "\n\n" +
        citations.map(citationSection).join("\n\n"),
    });
  }

  sections.forEach((s, i) => {
    out.push("---");
    out.push(`## ${i + 1}. ${s.title}`);
    out.push(s.body);
  });

  return [...out, ...footer(plan)].join("\n\n") + "\n";
}

interface ZipLike {
  file(name: string, data: string): void;
  generateAsync(opts: { type: "blob" }): Promise<Blob>;
}

async function loadJSZip(): Promise<new () => ZipLike> {
  const w = window as unknown as { JSZip?: new () => ZipLike };
  if (!w.JSZip) {
    await new Promise<void>((resolve, reject) => {
      const script = document.createElement("script");
      script.src = "https://cdnjs.cloudflare.com/ajax/libs/jszip/3.10.1/jszip.min.js";
      script.onload = () => resolve();
      script.onerror = () => reject(new Error("Failed to load JSZip"));
      document.head.appendChild(script);
    });
  }
  if (!w.JSZip) throw new Error("JSZip unavailable");
  return w.JSZip;
}

function triggerDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

// One .md per scanned company (plus 000-overview.md), bundled in a single
// zip — a browser would otherwise prompt for every one of up to 500 files.
export async function downloadBulkMarkdown(rows: MarkdownBulkRow[], plan: UserPlan): Promise<void> {
  const JSZip = await loadJSZip();
  const zip = new JSZip();
  const pad = Math.max(3, String(rows.length).length);
  zip.file(`${"0".repeat(pad)}-overview.md`, overviewMarkdown(rows, plan));
  rows.forEach((r, i) => {
    const n = String(i + 1).padStart(pad, "0");
    zip.file(`${n}-${slugFromUrl(r.url)}.md`, buildCompanyMarkdown(r, i + 1, plan));
  });
  const blob = await zip.generateAsync({ type: "blob" });
  triggerDownload(blob, `aiscope-bulk-${new Date().toISOString().slice(0, 19).replace(/[:T]/g, "-")}.zip`);
}
